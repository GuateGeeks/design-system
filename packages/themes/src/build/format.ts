import { buildNativeData, formatCssBlock } from '@guategeeks/tokens/build';
import type { Edition, ResolvedTheme, SchemeName } from '../types.ts';
import type { ThemeBuild } from './merge.ts';

/**
 * `[data-theme="id"]` holds the default scheme's full token set; each other scheme gets a
 * `[data-theme="id"][data-scheme="…"]` block with only the semantic colors that differ by scheme.
 */
export function formatThemeCss(build: Omit<ThemeBuild, 'css'>): string {
  const { resolved, tokens } = build;
  const [first, ...rest] = resolved.schemes;
  const parts: string[] = [];
  if (build.fontImport) parts.push(`@import "${build.fontImport}";\n`);
  if (first && tokens[first]) {
    parts.push(formatCssBlock(`[data-theme="${resolved.id}"]`, tokens[first]!, [`color-scheme: ${first};`]));
  }
  for (const scheme of rest) {
    const colors = (tokens[scheme] ?? []).filter((t) => t.layer === 'semantic' && t.path[0] === 'color');
    parts.push(formatCssBlock(`[data-theme="${resolved.id}"][data-scheme="${scheme}"]`, colors, [`color-scheme: ${scheme};`]));
  }
  return parts.join('\n');
}

/** Concatenates theme CSS with every `@import` hoisted (deduplicated) above the first rule. */
export function buildThemesCss(builds: Array<Pick<ThemeBuild, 'css'>>): string {
  const imports = new Set<string>();
  const bodies = builds.map((b) =>
    b.css.split('\n').filter((line) => {
      if (!line.startsWith('@import')) return true;
      imports.add(line);
      return false;
    }).join('\n').trim(),
  );
  return ['/* Generated by @guategeeks/themes. Do not edit. */', ...imports, '', ...bodies, ''].join('\n');
}

export function buildThemesTs(themes: ResolvedTheme[], editions: Edition[]): string {
  return `/* Generated by @guategeeks/themes. Do not edit. */
import type { Edition, ResolvedTheme } from '../types.ts';

export const themes: ResolvedTheme[] = ${JSON.stringify(themes, null, 2)};
export const editions: Edition[] = ${JSON.stringify(editions, null, 2)};
`;
}

export function buildThemesNativeTs(builds: Array<Omit<ThemeBuild, 'css'>>): string {
  const data: Record<string, Partial<Record<SchemeName, Record<string, string | number>>>> = {};
  for (const b of builds) {
    const entry: Partial<Record<SchemeName, Record<string, string | number>>> = {};
    for (const scheme of b.resolved.schemes) {
      const t = b.tokens[scheme] ?? [];
      entry[scheme] = buildNativeData(t, t).light;
    }
    data[b.resolved.id] = entry;
  }
  return `/* Generated by @guategeeks/themes. Do not edit. */
export const themes: Record<string, Partial<Record<'light' | 'dark', Record<string, string | number>>>> = ${JSON.stringify(data, null, 2)};
`;
}
