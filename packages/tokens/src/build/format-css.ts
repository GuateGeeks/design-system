import type { ResolvedToken } from './resolve.ts';

/** Semantic color roles, in the order the spec lists them. Components may only use these colors. */
export const COLOR_ROLES = [
  'bg', 'surface', 'surface-2', 'ink', 'ink-muted', 'ink-subtle', 'line', 'line-soft',
  'action', 'on-action', 'action-hover', 'link', 'focus', 'hero', 'on-hero', 'wash', 'accent',
  'ok', 'ok-soft', 'bad', 'bad-soft', 'hint', 'hint-soft',
] as const;
export type ColorRole = (typeof COLOR_ROLES)[number];

const DURATIONS = ['instant', 'fast', 'base', 'slow', 'epic'] as const;

const isSemanticColor = (t: ResolvedToken) => t.layer === 'semantic' && t.path[0] === 'color';

export function formatCssBlock(selector: string, tokens: ResolvedToken[], extra: string[] = []): string {
  const lines = tokens.map((t) => `  --${t.name}: ${t.value};`);
  return `${selector} {\n${[...lines, ...extra.map((l) => `  ${l}`)].join('\n')}\n}\n`;
}

/** The CSS reduced-motion rules. Their selectors outrank `[data-theme]`, so a theme's durations never win over reduced motion. */
export function reducedMotionCss(): string {
  const body = DURATIONS.map((d) => `  --gg-duration-${d}: 1ms;`).join('\n');
  return [
    `:root[data-motion="reduced"], [data-motion="reduced"] [data-theme] {\n${body}\n}\n`,
    `@media (prefers-reduced-motion: reduce) {\n:root:not([data-motion="full"]), :root:not([data-motion="full"]) [data-theme] {\n${body}\n}\n}\n`,
  ].join('\n');
}

export function buildCss(light: ResolvedToken[], dark: ResolvedToken[]): string {
  const darkColors = dark.filter(isSemanticColor);
  return [
    '/* Generated by @guategeeks/tokens. Do not edit. */\n',
    formatCssBlock(':root', light, ['color-scheme: light;']),
    formatCssBlock('[data-scheme="dark"]', darkColors, ['color-scheme: dark;']),
    `@media (prefers-color-scheme: dark) {\n${formatCssBlock(':root:where(:not([data-scheme]))', darkColors, ['color-scheme: dark;'])}}\n`,
    reducedMotionCss(),
  ].join('\n');
}
