import type { ResolvedToken } from './resolve.ts';

export type DurationName = 'instant' | 'fast' | 'base' | 'slow' | 'epic';
export type EasingName = 'standard' | 'responsive' | 'enter' | 'exit' | 'spring';

export interface TokenData {
  tokenNames: string[];
  light: Record<string, string | number>;
  dark: Record<string, string | number>;
  motion: { duration: Record<DurationName, number>; easing: Record<EasingName, string> };
}

export interface TokenJsonEntry {
  name: string;
  path: string[];
  layer: ResolvedToken['layer'];
  light: string | number;
  dark: string | number;
}

/** "0.24s" | "240ms" → 240 */
export function toMs(value: string | number): number {
  if (typeof value === 'number') return value;
  const n = parseFloat(value);
  return value.trim().endsWith('ms') ? n : Math.round(n * 1000);
}

const record = (tokens: ResolvedToken[]) => Object.fromEntries(tokens.map((t) => [`--${t.name}`, t.value]));

export function buildTokenData(light: ResolvedToken[], dark: ResolvedToken[]): TokenData {
  const duration = {} as Record<DurationName, number>;
  const easing = {} as Record<EasingName, string>;
  for (const t of light) {
    if (t.path[0] === 'duration') duration[t.path[1] as DurationName] = toMs(t.value);
    if (t.path[0] === 'easing') easing[t.path[1] as EasingName] = String(t.value);
  }
  return { tokenNames: light.map((t) => `--${t.name}`), light: record(light), dark: record(dark), motion: { duration, easing } };
}

export function buildTokenJson(light: ResolvedToken[], dark: ResolvedToken[]): TokenJsonEntry[] {
  const darkValues = record(dark);
  return light.map((t) => ({ name: `--${t.name}`, path: t.path, layer: t.layer, light: t.value, dark: darkValues[`--${t.name}`] ?? t.value }));
}

export function buildTs(data: TokenData): string {
  const names = JSON.stringify(data.tokenNames, null, 2);
  return `/* Generated by @guategeeks/tokens. Do not edit. */
export const tokenNames = ${names} as const;
export type TokenName = (typeof tokenNames)[number];
export const light: Record<TokenName, string | number> = ${JSON.stringify(data.light, null, 2)};
export const dark: Record<TokenName, string | number> = ${JSON.stringify(data.dark, null, 2)};
export const motion = ${JSON.stringify(data.motion, null, 2)} as const;
export type DurationToken = keyof typeof motion.duration;
export type EasingToken = keyof typeof motion.easing;
`;
}
