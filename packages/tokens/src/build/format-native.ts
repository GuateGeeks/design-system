import type { ResolvedToken } from './resolve.ts';
import { toMs } from './format-ts.ts';

export type NativeTokens = Record<string, string | number>;

const camel = (path: string[]) =>
  path.map((part, i) => {
    const words = part.split('-');
    return words.map((w, j) => (i === 0 && j === 0 ? w : w.charAt(0).toUpperCase() + w.slice(1))).join('');
  }).join('');

/** React Native wants unitless numbers: px stays, rem × 16, durations in ms. Other values (em, font stacks) stay strings. */
export function toNativeValue(token: ResolvedToken): string | number {
  const { value } = token;
  if (typeof value === 'number') return value;
  if (token.type === 'duration') return toMs(value);
  const px = /^(-?[\d.]+)px$/.exec(value);
  if (px) return Number(px[1]);
  const rem = /^(-?[\d.]+)rem$/.exec(value);
  if (rem) return Number(rem[1]) * 16;
  return value;
}

const native = (tokens: ResolvedToken[]): NativeTokens =>
  Object.fromEntries(tokens.map((t) => [camel(t.path), toNativeValue(t)]));

export function buildNativeData(light: ResolvedToken[], dark: ResolvedToken[]): { light: NativeTokens; dark: NativeTokens } {
  return { light: native(light), dark: native(dark) };
}

export function buildNativeTs(data: { light: NativeTokens; dark: NativeTokens }): string {
  return `/* Generated by @guategeeks/tokens. Do not edit. */
export const light: Record<string, string | number> = ${JSON.stringify(data.light, null, 2)};
export const dark: Record<string, string | number> = ${JSON.stringify(data.dark, null, 2)};
`;
}
